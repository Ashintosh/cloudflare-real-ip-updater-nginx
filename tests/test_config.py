import pytest

from cloudflare_nginx import (
    generate_cloudflare_config,
    generate_test_nginx_config,
    cleanup,
    install_new_config,
    try_restore_backup,
)


def test_generate_cloudflare_config():
    ip_ranges = [
        "192.0.2.0/24",
        "198.51.100.0/24",
        "2001:db8::/32",
    ]

    result = generate_cloudflare_config(ip_ranges)

    assert "set_real_ip_from 192.0.2.0/24;" in result
    assert "set_real_ip_from 198.51.100.0/24;" in result
    assert "set_real_ip_from 2001:db8::/32;" in result


def test_generate_cloudflare_config_empty():
    result = generate_cloudflare_config([])

    assert "set_real_ip_from" not in result
    assert "DO NOT EDIT THIS FILE MANUALLY." in result


def test_generate_cloudflare_config_has_header():
    result = generate_cloudflare_config([])

    assert result.startswith("#" + "=" * 40)
    assert "DO NOT EDIT THIS FILE MANUALLY." in result
    assert "automatically generated" in result


def test_generate_cloudflare_config_each_range_has_rule():
    ip_ranges = [
        "192.0.2.0/24",
        "198.51.100.0/24",
        "2001:db8::/32",
    ]

    result = generate_cloudflare_config(ip_ranges)

    lines = result.splitlines()

    rules = [
        line
        for line in lines
        if line.startswith("set_real_ip_from")
    ]

    assert rules == [
        "set_real_ip_from 192.0.2.0/24;",
        "set_real_ip_from 198.51.100.0/24;",
        "set_real_ip_from 2001:db8::/32;",
    ]


